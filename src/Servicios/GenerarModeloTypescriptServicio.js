const Fs = require("fs");
const Ruta = require("path");
const ConexionBaseDatos = require("../BaseDatos/ConexionBaseDatos");
const Sequelize = require("sequelize");
const { LanzarError } = require("../Utilidades/ErrorServicios");

const RutaModelos = Ruta.join(__dirname, "../Modelos");

const ObtenerTipoTypescript = (Atributo) => {
  const TipoNombre = Atributo.type.constructor.name.toLowerCase();

  if (TipoNombre.includes("string") || TipoNombre.includes("text") || TipoNombre.includes("uuid")) return "string";
  if (
    TipoNombre.includes("integer") ||
    TipoNombre.includes("float") ||
    TipoNombre.includes("decimal") ||
    TipoNombre.includes("number") ||
    TipoNombre.includes("tinyint") ||
    TipoNombre.includes("smallint") ||
    TipoNombre.includes("bigint")
  ) return "number";
  if (TipoNombre.includes("boolean")) return "boolean";
  if (TipoNombre.includes("date")) return "Date";

  return "any";
};

const TieneValorPredeterminado = (Atributo) =>
  Object.prototype.hasOwnProperty.call(Atributo, "defaultValue") &&
  Atributo.defaultValue !== undefined;

const GenerarModelos = async () => {
  if (!Fs.existsSync(RutaModelos)) {
    throw LanzarError(`Carpeta de modelos no encontrada: ${RutaModelos}`, 500, "Configuracion");
  }

  const archivos = Fs.readdirSync(RutaModelos).filter(archivo =>
    archivo.endsWith(".js") &&
    !["Relaciones.js", "init-models.js"].includes(archivo)
  );
  const ModelosTS = {};

  for (const archivo of archivos) {
    const RutaModelo = Ruta.join(RutaModelos, archivo);
    const DefinicionModelo = require(RutaModelo);
    let modelo;

    if (typeof DefinicionModelo === "function") {
      modelo = DefinicionModelo(ConexionBaseDatos, Sequelize.DataTypes);
    } else {
      modelo = DefinicionModelo;
    }

    const NombreModelo = archivo.replace(".js", "");

    if (!modelo || !modelo.rawAttributes) {
      console.warn(`⚠️ El modelo ${NombreModelo} no tiene atributos o rawAttributes. Se omite.`);
      continue;
    }

    let InterfazTS = `export interface ${NombreModelo} {\n`;

    for (const clave of Object.keys(modelo.rawAttributes)) {
      const Atributo = modelo.rawAttributes[clave];
      const TipoBaseTS = ObtenerTipoTypescript(Atributo);
      const AceptaNull = Atributo.allowNull !== false;
      const TipoTS = AceptaNull ? `${TipoBaseTS} | null` : TipoBaseTS;
      const EsOpcionalAlCrear = AceptaNull ||
        Atributo.autoIncrement === true ||
        Atributo._autoGenerated === true ||
        TieneValorPredeterminado(Atributo);

      InterfazTS += `  ${clave}${EsOpcionalAlCrear ? "?" : ""}: ${TipoTS};\n`;
    }

    InterfazTS += "}\n";
    ModelosTS[NombreModelo] = InterfazTS;
  }

  return ModelosTS;
};

module.exports = { GenerarModelos };